def crc8_calculate(data: bytes) -> int:
    """
    计算 CRC8 校验和

    使用查表法实现, 高效且稳定

    参数:
        data: 输入数据字节

    返回:
        CRC8 校验值 (0-255)
    """
    crc = 0
    for byte in data:
        crc = CRC8_TABLE[(crc ^ byte) & 0xFF]
    return crc


def crc8_verify(data: bytes, expected_crc: int) -> bool:
    """
    验证 CRC8 校验和

    参数:
        data: 输入数据 (不包含CRC字节)
        expected_crc: 期望的 CRC 值

    返回:
        True=校验通过, False=校验失败
    """
    return crc8_calculate(data) == expected_crc


def crc8_add(data: bytes) -> bytes:
    """
    为数据添加 CRC8 校验字节

    参数:
        data: 输入数据

    返回:
        追加了 CRC 字节的数据
    """
    crc = crc8_calculate(data)
    return data + bytes([crc])